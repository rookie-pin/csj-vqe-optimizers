    "def fd_gradient(f, x, h=1e-6):\n",
    "    g = np.zeros(len(x))\n",
    "    for i in range(len(x)):\n",
    "        e = np.zeros(len(x))\n",
    "        e[i] = h\n",
    "        g[i] = (f(x + e) - f(x - e)) / (2 * h)\n",
    "    return g\n",
